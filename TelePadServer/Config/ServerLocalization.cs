        public static string T(string key)
        {
            var lang = CurrentLanguage == "id" ? "id" : "en";
            if (_strings[lang].TryGetValue(key, out var val)) return val;
            if (_strings["en"].TryGetValue(key, out var fallback)) return fallback;
            return key;
        }

        public static string Tf(string key, params (string Key, object Value)[] args)
        {
            var result = T(key);
            foreach (var (k, v) in args)
            {
                result = result.Replace("{" + k + "}", v.ToString());
            }
            return result;
        }

        public static IReadOnlyDictionary<string, string> GetDictionary(string lang)
        {
            return lang == "id" ? _strings["id"] : _strings["en"];
